def _esc(value: Any) -> str:
    return html.escape(str(value), quote=True)


def _get_entry(hass: HomeAssistant) -> ConfigEntry | None:
    """Return the single Xiaodu config entry, if any."""
    entries = hass.config_entries.async_entries(DOMAIN)
    return entries[0] if entries else None


def _callback_origin(redirect_uri: str) -> str:
    """Return the scheme://netloc of the callback URL (used as OAuth client id)."""
    parts = urlparse(redirect_uri)
    return f"{parts.scheme}://{parts.netloc}"


def _redirect_uri_allowed(requested: str, configured: str) -> bool:
    """Accept the configured callback, or the same path on a known Xiaodu host.

    The Xiaodu console uses ``xiaodu.baidu.com`` in production and
    ``xiaodu-dbp.baidu.com`` for debug / mock testing; both are accepted so
    the console environment does not require a reconfigure.
    """
    if requested == configured:
        return True
    try:
        req = urlparse(requested)
        conf = urlparse(configured)
    except ValueError:
        return False
    return (
        req.scheme == "https"
        and (req.hostname or "") in CALLBACK_HOSTS
        and req.path == conf.path
        and not req.query
    )


async def _get_store(hass: HomeAssistant) -> XiaoduOAuthStore:
    """Return the shared OAuth store, loading persisted tokens on first use."""
    data = hass.data.setdefault(DOMAIN, {})
    if DATA_OAUTH_STORE not in data:
        store = XiaoduOAuthStore()
        storage = Store[dict[str, Any]](hass, STORAGE_VERSION, STORAGE_KEY)
        store.load_dict(await storage.async_load())
        data[DATA_OAUTH_STORE] = store
        data[DATA_OAUTH_STORAGE] = storage
    return data[DATA_OAUTH_STORE]


async def _save_store(hass: HomeAssistant) -> None:
    """Persist the current token store."""
    storage: Store[dict[str, Any]] = hass.data[DOMAIN][DATA_OAUTH_STORAGE]
    store: XiaoduOAuthStore = hass.data[DOMAIN][DATA_OAUTH_STORE]
    await storage.async_save(store.to_dict())


def _exposed_device_summary(hass: HomeAssistant, entry: ConfigEntry) -> str:
    """Return a human-readable summary of devices exposed to Xiaodu."""
    return summarize_devices(build_device_map(hass, entry.options))


