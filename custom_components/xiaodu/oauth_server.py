"""OAuth2 authorization server endpoints for the Xiaodu (DuerOS) skill.

The Xiaodu smart-home skill acts as the OAuth2 *client*: it redirects the user
to our authorize endpoint and then exchanges the returned authorization code
at our token endpoint.

Design notes (least privilege + security):

- The authorize endpoint authenticates the user through Home Assistant's own
  login flow (in-process, via ``hass.auth.login_flow``), but the token issued
  to the Xiaodu skill is an *opaque* random string owned by this integration,
  NOT a Home Assistant user token. The DuerOS endpoint only exposes
  entities allowed by the entry's device/capability config, so a leaked token cannot be
  used against the Home Assistant API with user-level permissions.
- ``state`` is required and echoed back, and every authorization is bound to a
  short-lived server-side session nonce stored in a SameSite=Strict cookie, so
  the login form cannot be driven cross-site (login CSRF).
- The login flow is driven generically step by step, so multi-step flows
  (e.g. two-factor authentication) work: each form step is rendered from the
  flow's data schema.
- Access tokens are short-lived; refresh tokens last longer and are rotated.
- Tokens are persisted in HA storage so they survive restarts.

Values to configure on the Xiaodu developer console:

- Authorize URL: {base}/api/xiaodu/oauth/authorize
- Token URL:    {base}/api/xiaodu/oauth/token
- WebService:   {base}/api/xiaodu/service (DCS multipart + plain JSON)
- Callback URL: generated by the platform (read-only, must match the one
                stored in the config entry)
"""

