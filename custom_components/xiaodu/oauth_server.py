def _access_log(kind: str, **fields: Any) -> None:
    """Emit one INFO access-log line per external Xiaodu interaction."""
    detail = " ".join(
        f"{key}={value}" for key, value in fields.items() if value not in (None, "")
    )
    _LOGGER.info("Xiaodu access: kind=%s %s", kind, detail)

